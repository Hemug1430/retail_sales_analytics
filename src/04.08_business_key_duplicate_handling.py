"""
Retail Sales Analytics
Tracker 04.08 - Handle Business-Key Duplicates

Requirement:
Detect multiple records sharing a business key and determine
insert, update, history, duplicate, or reject behavior.

This step:
1. Reads the output produced by 04.07.
2. Detects duplicate business keys efficiently.
3. Separates:
   - INSERT_CANDIDATE
   - DUPLICATE_SKIP
   - UPDATE_OR_HISTORY_REVIEW
   - REJECT
4. Preserves audit evidence.
5. Does NOT silently overwrite conflicting records.
"""

from pathlib import Path
import pandas as pd


# ============================================================
# PROJECT PATHS
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent

PROCESSED_DIR = PROJECT_ROOT / "data" / "processed"
OUTPUT_DIR = PROJECT_ROOT / "data" / "processed"

OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


# ============================================================
# DATASET BUSINESS-KEY DEFINITIONS
# ============================================================

BUSINESS_KEYS = {
    "customers": ["customer_id"],
    "products": ["product_id"],
    "stores": ["store_id"],
    "salespersons": ["salesperson_id"],
    "promotions": ["promotion_id"],
    "sales": ["sales_line_id"],
    "returns": ["return_id"],
    "targets": ["target_id"],
}


# ============================================================
# FIND 04.07 OUTPUT FILES
# ============================================================

def find_04_07_files():
    """
    Find files generated by Tracker 04.07.

    We deliberately look for filenames containing
    '04_07' and ending in '.csv'.
    """

    files = sorted(
        PROCESSED_DIR.glob("*04_07*.csv"),
        key=lambda p: p.stat().st_mtime,
        reverse=True
    )

    # Keep only one latest file for each dataset.
    selected = {}

    for file_path in files:
        name = file_path.name.lower()

        for dataset in BUSINESS_KEYS:
            if dataset in name and dataset not in selected:
                selected[dataset] = file_path
                break

    return selected


# ============================================================
# NORMALIZE DATASET NAME
# ============================================================

def identify_dataset(file_path):
    name = file_path.name.lower()

    for dataset in BUSINESS_KEYS:
        if dataset in name:
            return dataset

    return None


# ============================================================
# CHECK WHETHER TWO ROWS ARE EXACTLY THE SAME
# ============================================================

def rows_are_identical(row_a, row_b, key_columns):
    """
    Compare two rows excluding the business-key columns.
    """

    compare_columns = [
        col for col in row_a.index
        if col not in key_columns
    ]

    for column in compare_columns:
        value_a = row_a[column]
        value_b = row_b[column]

        if pd.isna(value_a) and pd.isna(value_b):
            continue

        if str(value_a) != str(value_b):
            return False

    return True


# ============================================================
# PROCESS ONE DATASET
# ============================================================

def process_dataset(dataset, input_file, business_key):

    print("\n" + "=" * 80)
    print(f"04.08 BUSINESS-KEY DUPLICATE HANDLING - {dataset.upper()}")
    print("=" * 80)

    print(f"Input file : {input_file}")
    print(f"Business key: {', '.join(business_key)}")

    try:
        df = pd.read_csv(
            input_file,
            encoding="utf-8-sig",
            dtype=str,
            keep_default_na=False
        )
    except Exception as exc:
        print(f"ERROR reading file: {exc}")
        return False

    rows_read = len(df)
    columns_read = len(df.columns)

    print(f"Rows read  : {rows_read:,}")
    print(f"Columns    : {columns_read}")

    # --------------------------------------------------------
    # Validate business-key columns
    # --------------------------------------------------------

    missing_keys = [
        key for key in business_key
        if key not in df.columns
    ]

    if missing_keys:
        print()
        print("STATUS : REJECT")
        print(
            "Missing business-key column(s): "
            + ", ".join(missing_keys)
        )

        audit_file = (
            OUTPUT_DIR
            / f"04_08_{dataset}_business_key_duplicate_audit.csv"
        )

        audit_df = pd.DataFrame([{
            "dataset": dataset,
            "input_file": str(input_file),
            "rows_read": rows_read,
            "business_key": "|".join(business_key),
            "status": "REJECT",
            "reason": "Missing business-key column",
            "missing_columns": "|".join(missing_keys),
        }])

        audit_df.to_csv(
            audit_file,
            index=False,
            encoding="utf-8-sig"
        )

        return False

    # --------------------------------------------------------
    # Clean key values only for comparison
    # --------------------------------------------------------

    comparison_df = df.copy()

    for key in business_key:
        comparison_df[key] = (
            comparison_df[key]
            .astype(str)
            .str.strip()
        )

    # --------------------------------------------------------
    # Identify blank business keys
    # --------------------------------------------------------

    blank_key_mask = pd.Series(False, index=df.index)

    for key in business_key:
        blank_key_mask = (
            blank_key_mask
            | comparison_df[key].eq("")
            | comparison_df[key].isna()
        )

    blank_key_count = int(blank_key_mask.sum())

    # --------------------------------------------------------
    # Duplicate-key groups
    # --------------------------------------------------------

    valid_df = comparison_df.loc[~blank_key_mask].copy()

    duplicate_key_mask = valid_df.duplicated(
        subset=business_key,
        keep=False
    )

    duplicate_key_rows = valid_df.loc[duplicate_key_mask].copy()

    # --------------------------------------------------------
    # Counters
    # --------------------------------------------------------

    insert_candidates = 0
    duplicate_skip_rows = 0
    update_history_review_rows = 0
    reject_rows = blank_key_count

    actions = [""] * len(df)
    reasons = [""] * len(df)

    # --------------------------------------------------------
    # Blank business keys -> REJECT
    # --------------------------------------------------------

    for idx in df.index[blank_key_mask]:
        actions[idx] = "REJECT"
        reasons[idx] = "Blank business key"

    # --------------------------------------------------------
    # Process unique business keys
    # --------------------------------------------------------

    unique_mask = ~valid_df.duplicated(
        subset=business_key,
        keep=False
    )

    unique_indices = valid_df.index[unique_mask]

    for idx in unique_indices:
        actions[idx] = "INSERT_CANDIDATE"
        reasons[idx] = "Business key unique"

    insert_candidates += len(unique_indices)

    # --------------------------------------------------------
    # Process duplicate business-key groups
    # --------------------------------------------------------

    if not duplicate_key_rows.empty:

        grouped = duplicate_key_rows.groupby(
            business_key,
            sort=False,
            dropna=False
        )

        for _, group in grouped:

            group_indices = list(group.index)

            # ------------------------------------------------
            # Determine whether all duplicate rows are
            # exactly identical apart from the business key.
            # ------------------------------------------------

            first_row = group.iloc[0]

            all_identical = True

            for row_position in range(1, len(group)):
                current_row = group.iloc[row_position]

                if not rows_are_identical(
                    first_row,
                    current_row,
                    business_key
                ):
                    all_identical = False
                    break

            # ------------------------------------------------
            # Exact duplicate business-key records
            # ------------------------------------------------

            if all_identical:

                first_index = group_indices[0]

                actions[first_index] = "INSERT_CANDIDATE"
                reasons[first_index] = (
                    "First occurrence of exact duplicate business-key group"
                )

                insert_candidates += 1

                for duplicate_index in group_indices[1:]:
                    actions[duplicate_index] = "DUPLICATE_SKIP"
                    reasons[duplicate_index] = (
                        "Exact duplicate of same business-key record"
                    )

                    duplicate_skip_rows += 1

            # ------------------------------------------------
            # Conflicting records sharing same business key
            # ------------------------------------------------

            else:

                for duplicate_index in group_indices:
                    actions[duplicate_index] = (
                        "UPDATE_OR_HISTORY_REVIEW"
                    )

                    reasons[duplicate_index] = (
                        "Multiple records share business key "
                        "with conflicting attribute values"
                    )

                    update_history_review_rows += 1

    # --------------------------------------------------------
    # Safety check
    # --------------------------------------------------------

    unresolved = [
        i for i, action in enumerate(actions)
        if action == ""
    ]

    if unresolved:
        for idx in unresolved:
            actions[idx] = "REJECT"
            reasons[idx] = "Unable to classify record"

        reject_rows += len(unresolved)

    # --------------------------------------------------------
    # Attach audit classification to output
    # --------------------------------------------------------

    output_df = df.copy()

    output_df["_04_08_action"] = actions
    output_df["_04_08_reason"] = reasons

    # --------------------------------------------------------
    # Output file
    # --------------------------------------------------------

    output_file = (
        OUTPUT_DIR
        / f"{input_file.stem}_04_08_business_key_duplicates_handled.csv"
    )

    output_df.to_csv(
        output_file,
        index=False,
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # Audit summary
    # --------------------------------------------------------

    audit_file = (
        OUTPUT_DIR
        / f"04_08_{dataset}_business_key_duplicate_audit.csv"
    )

    audit_df = pd.DataFrame([{
        "dataset": dataset,
        "input_file": input_file.name,
        "business_key": "|".join(business_key),
        "rows_read": rows_read,
        "columns_read": columns_read,
        "insert_candidates": insert_candidates,
        "duplicate_skip_rows": duplicate_skip_rows,
        "update_or_history_review_rows": update_history_review_rows,
        "reject_rows": reject_rows,
        "blank_business_key_rows": blank_key_count,
        "status": (
            "PASS"
            if reject_rows == 0
            else "REVIEW"
        ),
    }])

    audit_df.to_csv(
        audit_file,
        index=False,
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # Console output
    # --------------------------------------------------------

    print()
    print("BUSINESS-KEY DUPLICATE SUMMARY")
    print("-" * 80)
    print(f"Total rows processed          : {rows_read:,}")
    print(f"Insert candidates             : {insert_candidates:,}")
    print(f"Duplicate/skip rows           : {duplicate_skip_rows:,}")
    print(
        "Update/history review rows    : "
        f"{update_history_review_rows:,}"
    )
    print(f"Reject rows                   : {reject_rows:,}")

    print()
    print(f"Processed output:")
    print(output_file)

    print()
    print(f"Audit output:")
    print(audit_file)

    return True


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 80)
    print("TRACKER 04.08 - HANDLE BUSINESS-KEY DUPLICATES")
    print("=" * 80)

    files = find_04_07_files()

    if not files:
        print()
        print("ERROR: No 04.07 output files were found.")
        print(f"Checked folder: {PROCESSED_DIR}")
        return

    print()
    print(f"04.07 dataset files found: {len(files)}")

    completed = 0
    failed = 0

    # --------------------------------------------------------
    # Process every discovered dataset
    # --------------------------------------------------------

    for dataset, input_file in files.items():

        business_key = BUSINESS_KEYS[dataset]

        success = process_dataset(
            dataset=dataset,
            input_file=input_file,
            business_key=business_key
        )

        if success:
            completed += 1
        else:
            failed += 1

    # --------------------------------------------------------
    # Overall result
    # --------------------------------------------------------

    print()
    print("=" * 80)
    print("04.08 OVERALL RESULT")
    print("=" * 80)

    print(f"Datasets processed : {completed}")
    print(f"Datasets requiring review/reject : {failed}")

    if completed > 0:
        print()
        print(
            "Business-key duplicate handling completed. "
            "Exact duplicates were classified for skipping, "
            "unique records were classified as insert candidates, "
            "and conflicting business-key records were routed "
            "for update/history review rather than silently overwritten."
        )

    print()
    print("=" * 80)
    print("Tracker 04.08 business-key duplicate handling processing completed.")
    print("=" * 80)


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()